/** Builds reports/SPONSOR_BEHAVIOUR.md from the raw place/cancel run records. */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

type Step = { step: string; ms: number; detail?: Record<string, unknown> }
type Run = { runId: string; side: string; summary: Record<string, string>; steps: Step[] }

const dir = join(process.cwd(), 'reports', 'live-runs')
const runs: Run[] = readdirSync(dir)
  .filter((f) => !f.startsWith('flip-'))
  .sort()
  .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')))

const at = (r: Run, name: string) => r.steps.find((s) => s.step === name)?.ms
const delta = (r: Run, a: string, b: string) => {
  const x = at(r, a)
  const y = at(r, b)
  return x === undefined || y === undefined ? 'n/a' : `${y - x}`
}

const rows = runs.map((r) =>
  [
    r.runId,
    r.side,
    r.summary.orderId,
    delta(r, 'placeFlip.submitted', 'placeFlip.included'),
    delta(r, 'placeFlip.included', 'getOrder.readback'),
    delta(r, 'cancel.submitted', 'cancel.included'),
    delta(r, 'cancel.included', 'getOrder.afterCancel'),
    r.steps.find((s) => s.step === 'getOrder.afterCancel')?.detail?.result ?? 'n/a',
  ].join(' | '),
)

const md = `# Sponsor behaviour calibration (PRD §12.4, addendum A2)

Generated by \`scripts/behaviour-report.ts\` from \`reports/live-runs/*.json\`. Network: Tempo Moderato testnet (42431), RPC \`https://rpc.moderato.tempo.xyz\`, viem 2.57.4. Times in milliseconds measured from this machine (Lagos, WAT), so they include public-internet RPC latency.

| run_id | side | orderId | submit → receipt | receipt → getOrder readback | cancel submit → receipt | cancel receipt → absent readback | postcondition |
|---|---|---|---:|---:|---:|---:|---|
${rows.map((r) => `| ${r} |`).join('\n')}

With ${runs.length} observations these are examples, not percentiles. What the product does with them: transaction stages are shown as they happen (Signing → Submitted → Included → Verifying → Confirmed), with no artificial pacing. Each stage takes about a second on this network, so the "Verifying with Tempo" step stays visible only as long as the readback actually takes.

Failed paths seen: none in place/cancel. Read-path failures (\`getTickLevel\` gas exhaustion and gateway timeouts) are documented in \`SPONSOR_FINDINGS.md\`.
`
writeFileSync(join(process.cwd(), 'reports', 'SPONSOR_BEHAVIOUR.md'), md)
console.log(md)
